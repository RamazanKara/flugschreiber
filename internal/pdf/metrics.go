// Glyph advance widths for the standard PDF fonts, in thousandths of the font
// size, indexed by WinAnsiEncoding code. Codes WinAnsi leaves undefined are
// zero and are never produced by the encoder in font.go.
//
// Derived from the URW Nimbus AFM files shipped with Ghostscript and TeX Live
// by mapping each WinAnsi code to its glyph name and looking up WX. A viewer
// supplies the glyphs, so these numbers have to agree with the ones the viewer
// uses, which for a non-embedded standard font are the Adobe base-14 metrics.
//
// URW is not metrically identical to Adobe everywhere. It disagrees on degree,
// the superior digits and the vulgar fractions, and it gives the oblique faces
// widths that differ from the upright, which Adobe never does. Those codes were
// corrected by hand against the Adobe AFMs and are pinned in font_test.go, so
// regenerating from URW without applying the same corrections will fail the
// tests rather than quietly move text.
//
// Courier is not listed because every one of its glyphs advances by 600.

